/// In the browser: the page's address picks the page, the units' long text is fetched, and the
/// app draws the page afresh into `#app` in place of the pre-rendered HTML. Yew renders in a
/// microtask, so the swap happens before the next paint (the text never blinks); the scroll
/// the visitor may already have made is kept.
#[cfg(target_arch = "wasm32")]
fn main() {
    use route::Page;
    let win = web_sys::window().expect("window");
    let doc = win.document().expect("document");
    let path = win.location().pathname().unwrap_or_default();
    let page = Page::parse(&path).unwrap_or(Page::new(lang::Lang::En, route::Route::Home));
    let root = match doc.get_element_by_id("app") {
        Some(r) => r,
        None => {
            let r = doc.create_element("div").expect("div");
            r.set_id("app");
            let _ = doc.body().expect("body").append_child(&r);
            r
        }
    };
    wasm_bindgen_futures::spawn_local(async move {
        // The units' long text first, so the app's first render says what the page says.
        unit_text::load().await;
        let y = win.scroll_y().unwrap_or(0.0);
        root.set_inner_html("");
        yew::Renderer::<app::App>::with_root_and_props(root, app::AppProps { page }).render();
        // Yew renders in a microtask: this runs after it, before the next paint.
        wasm_bindgen_futures::spawn_local(async move { after(win, y) });
    });
}

/// Once the app has drawn the page: real heights from here on, and the visitor's scroll kept.
#[cfg(target_arch = "wasm32")]
fn after(win: web_sys::Window, y: f64) {
    // The bands' lazy layout was for the first paint (frame.css): from here on, real heights.
    if let Some(root) = win.document().and_then(|d| d.document_element()) {
        let _ = root.class_list().add_1("app-on");
    }
    if y > 0.0 && (win.scroll_y().unwrap_or(0.0) - y).abs() > 1.0 {
        win.scroll_to_with_x_and_y(0.0, y);
    }
}

/// Natively, with the `ssr` feature: `prerender <dist> [--lastmod YYYY-MM-DD]`.
#[cfg(all(not(target_arch = "wasm32"), feature = "ssr"))]
fn main() {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let rest = match args.first().map(String::as_str) {
        Some("prerender") => &args[1..],
        _ => {
            eprintln!("usage: cantus-web prerender <dist> [--lastmod YYYY-MM-DD]");
            std::process::exit(2);
        }
    };
    if let Err(e) = prerender::run(rest) {
        eprintln!("prerender: {e}");
        std::process::exit(1);
    }
}

