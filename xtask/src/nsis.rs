//! The installer's script: `xtask/installer/cantus.nsi` is written by hand and reviewed
//! like code; what changes with each build — the version, the file list, the strings — is
//! generated beside it into `target/package/nsis/<flavour>/` as three includes:
//!
//! - `config.nsh` — the version, the output, the icon, the licence, the signing hook;
//! - `files.nsh` — one `File` per staged file, and the matching `Delete`s and `RMDir`s, so
//!   the uninstaller removes exactly what the installer wrote and nothing else;
//! - `strings.nsh` — the installer's words in English and Spanish, read from the app's
//!   own locale area (`locales/areas/update.*`, keys `update.installer.*`).

use crate::archive::Entry;
use crate::package::Staged;
use cantus_update::release::Flavor;
use std::collections::BTreeSet;
use std::path::{Path, PathBuf};

pub struct Config {
    pub version: String,
    pub flavor: Flavor,
    pub outfile: PathBuf,
    pub icon: Option<PathBuf>,
    pub license: PathBuf,
    pub uninst_sign: Option<String>,
}

/// NSIS string escaping inside double quotes.
pub fn escape(s: &str) -> String {
    s.replace('$', "$$")
        .replace('"', "$\\\"")
        .replace("\r\n", "\n")
        .replace('\n', "$\\r$\\n")
}

fn win(p: &Path) -> String {
    escape(&p.display().to_string())
}

/// `0.2.0-rc.1` → `0.2.0.0`: the four numbers Windows' version resource wants.
pub fn version4(v: &str) -> String {
    let core = v.split(['-', '+']).next().unwrap_or(v);
    let mut n: Vec<&str> = core.split('.').collect();
    n.resize(3, "0");
    format!("{}.{}.{}.0", n[0], n[1], n[2])
}

/// Install and remove lines for `entries` under `root` — an NSIS path expression such as
/// `$INSTDIR` or `${CLAP_DIR}`, written as it is; only the names below it are escaped.
fn block(entries: &[Entry], root: &str) -> (String, String) {
    let mut install = String::new();
    let mut remove = String::new();
    let mut dirs: BTreeSet<String> = BTreeSet::new();
    let mut current: Option<String> = None;
    for e in entries {
        let (dir, _file) = match e.name.rsplit_once('/') {
            Some((d, f)) => (format!("{root}\\{}", escape(&d.replace('/', "\\"))), f),
            None => (root.to_owned(), e.name.as_str()),
        };
        if current.as_deref() != Some(dir.as_str()) {
            install.push_str(&format!("  SetOutPath \"{dir}\"\n"));
            current = Some(dir.clone());
        }
        install.push_str(&format!("  File \"{}\"\n", win(&e.src)));
        remove.push_str(&format!(
            "  Delete \"{}\\{}\"\n",
            root,
            escape(&e.name.replace('/', "\\"))
        ));
        // Every folder between the file and the root, to remove once empty.
        let mut d = e.name.as_str();
        while let Some((parent, _)) = d.rsplit_once('/') {
            dirs.insert(parent.to_owned());
            d = parent;
        }
    }
    // Deepest first, then the root itself; RMDir without /r only removes empty folders,
    // so anything the user put there stays.
    let mut sorted: Vec<&String> = dirs.iter().collect();
    sorted.sort_by_key(|d| std::cmp::Reverse(d.matches('/').count()));
    for d in sorted {
        remove.push_str(&format!(
            "  RMDir \"{}\\{}\"\n",
            root,
            escape(&d.replace('/', "\\"))
        ));
    }
    remove.push_str(&format!("  RMDir \"{root}\"\n"));
    (install, remove)
}

pub fn files_nsh(s: &Staged) -> String {
    let mut out = String::from("; Generated by `cargo run -p xtask -- package`. Do not edit.\n\n");
    for (name, list, root) in [
        ("APP", &s.app, "$INSTDIR"),
        ("CLAP", &s.clap, "${CLAP_DIR}"),
        ("VST3", &s.vst3, "${VST3_DIR}"),
    ] {
        let (install, remove) = block(list, root);
        // The install folder itself is removed by the uninstaller after uninstall.exe.
        let remove = if name == "APP" {
            remove.replace("  RMDir \"$INSTDIR\"\n", "")
        } else {
            remove
        };
        out.push_str(&format!(
            "!macro CANTUS_{name}_FILES\n{install}!macroend\n\n!macro CANTUS_{name}_REMOVE\n{remove}!macroend\n\n"
        ));
    }
    let bytes: u64 = s
        .app
        .iter()
        .chain(&s.clap)
        .chain(&s.vst3)
        .filter_map(|e| e.src.metadata().ok())
        .map(|m| m.len())
        .sum();
    out.push_str(&format!("!define EST_SIZE_KB {}\n", bytes.div_ceil(1024)));
    out
}

/// `key = value` lines (the app's locale format; `\n` is a line break).
pub fn locale_pairs(text: &str) -> Vec<(String, String)> {
    text.lines()
        .map(str::trim_start)
        .filter(|l| !l.is_empty() && !l.starts_with('#'))
        .filter_map(|l| l.split_once('='))
        .map(|(k, v)| (k.trim().to_owned(), v.trim().replace("\\n", "\n")))
        .collect()
}

/// `LangString`s for every `update.installer.*` key: `CANTUS_<REST>` in upper case.
pub fn strings_nsh(en: &str, es: &str) -> String {
    let mut out = String::from("; Generated from locales/areas/update.{en,es}.txt. Do not edit.\n");
    for (lang, text) in [("ENGLISH", en), ("SPANISH", es)] {
        for (k, v) in locale_pairs(text) {
            if let Some(rest) = k.strip_prefix("update.installer.") {
                let name = rest.to_ascii_uppercase().replace('.', "_");
                out.push_str(&format!(
                    "LangString CANTUS_{name} ${{LANG_{lang}}} \"{}\"\n",
                    escape(&v)
                ));
            }
        }
    }
    out
}

pub fn config_nsh(c: &Config) -> String {
    let (flavor, label) = match c.flavor {
        Flavor::Standard => ("standard", ""),
        Flavor::Asio => ("asio", " (ASIO)"),
    };
    let mut out = String::from("; Generated by `cargo run -p xtask -- package`. Do not edit.\n");
    out.push_str(&format!("!define VERSION \"{}\"\n", escape(&c.version)));
    out.push_str(&format!("!define VERSION4 \"{}\"\n", version4(&c.version)));
    out.push_str(&format!("!define FLAVOR \"{flavor}\"\n"));
    out.push_str(&format!("!define FLAVOR_LABEL \"{label}\"\n"));
    out.push_str(&format!("!define OUTFILE \"{}\"\n", win(&c.outfile)));
    out.push_str(&format!("!define LICENSE_FILE \"{}\"\n", win(&c.license)));
    if let Some(icon) = &c.icon {
        out.push_str(&format!("!define ICON \"{}\"\n", win(icon)));
    }
    if let Some(cmd) = &c.uninst_sign {
        // Single quotes: the command holds double quotes of its own. It runs in the
        // script's folder, so its program path must be absolute.
        out.push_str(&format!("!uninstfinalize '{cmd}' = 0\n"));
    }
    out
}

/// Write the three includes and the script into `work`; returns the script's path.
pub fn write_work(work: &Path, s: &Staged, c: &Config) -> PathBuf {
    let ws = crate::workspace();
    let _ = std::fs::remove_dir_all(work);
    std::fs::create_dir_all(work).unwrap();
    let locales = ws.join("crates/cantus-ui/locales/areas");
    let read = |p: PathBuf| {
        std::fs::read_to_string(&p).unwrap_or_else(|e| panic!("read {}: {e}", p.display()))
    };
    let en = read(locales.join("update.en.txt"));
    let es = read(locales.join("update.es.txt"));
    std::fs::write(work.join("config.nsh"), config_nsh(c)).unwrap();
    std::fs::write(work.join("files.nsh"), files_nsh(s)).unwrap();
    std::fs::write(work.join("strings.nsh"), strings_nsh(&en, &es)).unwrap();
    let nsi = work.join("cantus.nsi");
    std::fs::copy(ws.join("xtask/installer/cantus.nsi"), &nsi).unwrap();
    // The ASIO flavour's optional FlexASIO step (the script is the same for both).
    std::fs::copy(
        ws.join("xtask/installer/flexasio.ps1"),
        work.join("flexasio.ps1"),
    )
    .unwrap();
    nsi
}

/// `makensis.exe`: `CANTUS_MAKENSIS`, the `PATH`, a portable copy unzipped into
/// `%LOCALAPPDATA%\cantus-build-tools\nsis-*`, or NSIS's own install folder.
pub fn makensis() -> Option<PathBuf> {
    if let Some(p) = std::env::var_os("CANTUS_MAKENSIS") {
        return Some(PathBuf::from(p));
    }
    let exe = if cfg!(windows) {
        "makensis.exe"
    } else {
        "makensis"
    };
    if let Some(path) = std::env::var_os("PATH") {
        for d in std::env::split_paths(&path) {
            if d.join(exe).is_file() {
                return Some(d.join(exe));
            }
        }
    }
    if let Some(local) = std::env::var_os("LOCALAPPDATA") {
        let tools = PathBuf::from(local).join("cantus-build-tools");
        let mut found: Vec<PathBuf> = std::fs::read_dir(&tools)
            .into_iter()
            .flatten()
            .filter_map(Result::ok)
            .map(|e| e.path())
            .filter(|p| {
                p.file_name()
                    .is_some_and(|n| n.to_string_lossy().starts_with("nsis-"))
                    && p.join(exe).is_file()
            })
            .collect();
        found.sort();
        if let Some(p) = found.pop() {
            return Some(p.join(exe));
        }
    }
    [r"C:\Program Files (x86)\NSIS", r"C:\Program Files\NSIS"]
        .iter()
        .map(|d| Path::new(d).join(exe))
        .find(|p| p.is_file())
}
