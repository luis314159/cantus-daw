macro_rules! preset {
    ($label:expr, [$($v:expr),* $(,)?], [$($t:expr),* $(,)?], [$($tag:expr),* $(,)?]) => {
        FactoryPreset {
            label_key: $label,
            values: &[$($v),*],
            text: &[$($t),*],
            tags: &[$($tag),*],
        }
    };
}

