//! Exemplar's factory presets. No recorded content ships yet (the licence ruling is open),
//! so every preset is a real multisampled instrument built from the **built-in sounds**
//! computed at start-up (`cantus_dsp::exemplar::builtin`): plucked strings sampled at
//! three roots and crossfaded across the keys, bells in two velocity layers, a looped
//! pad, a round-robin kit with a choked hi-hat, an organ with a key-click release sample.
//! Each names what its macros do.
//!
//! Built-in numbers (`z{n}.gen`): 1 sine, 2 saw, 3 square, 4 triangle, 5 noise,
//! 6–8 pluck C2/C4/C6, 9–10 bell soft/hard, 11 pad, 12 kick, 13–15 snares, 16–17 closed
//! hats, 18 open hat, 19 key click, 20 organ, 21 choir (checked by the DSP's tests).

