macro_rules! preset {
    ($label:literal, $text:expr, $tags:expr, [$($k:literal => $v:expr),* $(,)?]) => {
        FactoryPreset {
            label_key: $label,
            values: &[
                ("mod1.amt", -0.35),
                ("mod2.amt", 0.3),
                ("mod3.amt", 0.4),
                ("mod4.amt", 0.25),
                $(($k, $v)),*
            ],
            text: $text,
            tags: $tags,
        }
    };
}

