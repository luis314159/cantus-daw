pub fn param(key: &str) -> Option<&'static InstParamInfo> {
    find(PARAMS, key)
        .or_else(|| {
            key.starts_with("card")
                .then(|| find(CARD_PARAMS, key))
                .flatten()
        })
        .or_else(|| super::modulation::param(key))
}

pub fn is_text_key(key: &str) -> bool {
    super::modulation::is_text_key(key)
}

pub fn is_asset_key(key: &str) -> bool {
    let _ = key;
    false
}

/// The named stops of the Condition control, as label keys, with the value each names.
pub const CONDITION_STOPS: [(f32, &str); 5] = [
    (0.0, "calor.condition.calibrated"),
    (0.25, "calor.condition.settled"),
    (0.5, "calor.condition.worn"),
    (0.75, "calor.condition.weathered"),
    (1.0, "calor.condition.unruly"),
];

/// The stop a Condition value reads as (the nearest).
pub fn condition_stop(v: f32) -> &'static str {
    CONDITION_STOPS
        .iter()
        .min_by(|a, b| (a.0 - v).abs().total_cmp(&(b.0 - v).abs()))
        .map(|s| s.1)
        .unwrap_or(CONDITION_STOPS[0].1)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::inst::{InstrumentKind, NativeSpec};

    #[test]
    fn every_label_is_calors_own_and_every_card_can_be_rerolled() {
        for info in PARAMS {
            assert!(
                info.label_key.starts_with("calor.") || info.key == "gain",
                "{}",
                info.key
            );
        }
        for (c, key) in CARD_ROLL_KEYS.iter().enumerate() {
            assert_eq!(*key, format!("card{}.roll", c + 1));
            assert!(param(key).is_some());
            assert!(!PARAMS.iter().any(|i| i.key == *key));
        }
        let mut s = NativeSpec::new(InstrumentKind::Analog);
        assert_eq!(s.set("card16.roll", 3.4), Some(3.0));
        assert_eq!(param("card17.roll"), None);
    }

    #[test]
    fn the_condition_reads_as_its_nearest_stop() {
        assert_eq!(condition_stop(0.0), "calor.condition.calibrated");
        assert_eq!(condition_stop(0.3), "calor.condition.settled");
        assert_eq!(condition_stop(0.99), "calor.condition.unruly");
    }
}
