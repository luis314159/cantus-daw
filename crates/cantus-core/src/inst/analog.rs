//! Calor — the analog-modelling polysynth: its parameter model (ADR 0023,
//! `research/instruments/analog.md` §8.6). Owned by this instrument's builder.
//!
//! A fixed signal path read left to right — three oscillators, a sub and noise into a
//! mixer whose levels drive the filter, a high-pass, the filter (five topologies in one
//! slot), the amplifier — with two envelopes, two LFOs, the wheel and poly-mod as fixed
//! routings, the shared matrix for everything else, and **analog variance, seeded**: one
//! Condition control over drift and sixteen voice cards whose calibration errors come
//! from a seed (and a per-card re-roll).
//!
//! Units are the ones a player reads: Hz, ms, s, dB, cents, semitones, octaves; a `%`
//! parameter is stored as a fraction (the knobs print it ×100), so resonance 1.0 is
//! "100 %", the self-oscillation threshold. An enum is its index, a switch 0/1. Keys are
//! forever once shipped.

