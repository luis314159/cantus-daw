"""The guitar family's pixel fit: the 12, 14, 15 and 16-px drawings as pixel rows.

    python fit.py            -> glyphs-t-guitars-px.js

sheet-guitars.html?mode=fit draws every chosen guitar at those sizes as a vector 8x larger, in
pure inks (main red, second green, cut black, on black). Each device pixel is an 8 x 8 block;
its coverage of each ink picks the pixel's character in family.js's notation:
    '#' main >= 0.55   '*' main >= 0.30   'O' second >= 0.5   'o' second >= 0.25   '+' main >= 0.15
so an edge is either in or out, or one of two steps of the main ink — never the 10-20 % grey
fringe that made the vector drawings soft at 14 px. The rows are then read at 4x and corrected
by hand in glyphs-t-guitars-px-fix.js (which wins).
"""
import html
import json
import os
import re

from PIL import Image

import render

HERE = os.path.dirname(os.path.abspath(__file__))
Z, CELL = 8, 16 * 8 + 8


def char(r, g):
    if r >= 0.55:
        return '#'
    if r >= 0.30 and r >= g:
        return '*'
    if g >= 0.5:
        return 'O'
    if g >= 0.25:
        return 'o'
    if r >= 0.15:
        return '+'
    return '.'


def main():
    url = render.url_for('sheet-guitars.html', 'mode=fit')
    dom = render.edge(['--dump-dom', url]).stdout
    w = int(re.search(r'data-w="(\d+)"', dom).group(1))
    h = int(re.search(r'data-h="(\d+)"', dom).group(1))
    m = json.loads(html.unescape(re.search(r'data-map="([^"]*)"', dom).group(1)))
    out = os.path.join(os.environ.get('TEMP', HERE), 'cantus-guitars-fit.png')
    render.edge(['--force-device-scale-factor=1', f'--window-size={w},{h}', f'--screenshot={out}', url])
    im = Image.open(out).convert('RGB')
    px = im.load()
    lines = ['// Generated by fit.py from sheet-guitars.html?mode=fit — do not edit; corrections go in',
             '// glyphs-t-guitars-px-fix.js. The guitar family at 12, 14, 15 and 16 px as pixel rows.',
             '(() => {', '  if (/mode=fit/.test(location.search)) return;', '  const N = window.N;',
             '  const P = (id, S, rows) => { if (!N[id]._px) N[id] = Object.assign({ _px: 1 }, N[id]); N[id][S] = { px: [{ at: [0, 0], rows }] }; };']
    for id_, S, x0, y0 in m:
        rows = []
        for y in range(S):
            row = ''
            for x in range(S):
                rs = gs = 0
                for dy in range(Z):
                    for dx in range(Z):
                        r, g, _ = px[x0 + x * Z + dx, y0 + y * Z + dy]
                        rs += r
                        gs += g
                row += char(rs / (255 * Z * Z), gs / (255 * Z * Z))
            rows.append(row)
        lines.append(f"  P('{id_}', {S}, [")
        lines += [f"    '{r}'," for r in rows]
        lines.append('  ]);')
    lines += ['})();', '']
    with open(os.path.join(HERE, 'glyphs-t-guitars-px.js'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines))
    print(f'{len(m)} drawings fitted')


if __name__ == '__main__':
    main()
