"""Writes crates/cantus-score/src/glyphs_meta.rs: the SMuFL glyphs the engraver uses, with
Bravura's bounding boxes, advance widths and stem anchors, and its engraving defaults.

    python -I tools/score/gen_bravura.py <Bravura.json> <glyphnames.json> > crates/cantus-score/src/glyphs_meta.rs

Bravura.json is the font's metadata (github.com/steinbergmedia/bravura, redist/), the same
release as crates/cantus-score/assets/Bravura.otf; glyphnames.json is SMuFL's
(github.com/w3c/smufl, metadata/). Neither file is kept in the repository: what the
engraver reads of them is this generated table.
"""

import json
import sys

GLYPHS = """
gClef fClef cClef gClef8vb gClef8va gClef15ma fClef8vb gClefChange fClefChange
timeSig0 timeSig1 timeSig2 timeSig3 timeSig4 timeSig5 timeSig6 timeSig7 timeSig8 timeSig9
timeSigCommon timeSigCutCommon
noteheadDoubleWhole noteheadWhole noteheadHalf noteheadBlack
flag8thUp flag8thDown flag16thUp flag16thDown flag32ndUp flag32ndDown flag64thUp flag64thDown
restDoubleWhole restWhole restHalf restQuarter rest8th rest16th rest32nd rest64th
restWholeLegerLine restHalfLegerLine
accidentalFlat accidentalNatural accidentalSharp accidentalDoubleSharp accidentalDoubleFlat
accidentalParensLeft accidentalParensRight
augmentationDot
tuplet0 tuplet1 tuplet2 tuplet3 tuplet4 tuplet5 tuplet6 tuplet7 tuplet8 tuplet9 tupletColon
dynamicPiano dynamicMezzo dynamicForte dynamicPPP dynamicPP dynamicMP dynamicMF dynamicFF dynamicFFF
metNoteWhole metNoteHalfUp metNoteQuarterUp metNote8thUp metNote16thUp metAugmentationDot
brace ottava ottavaAlta ottavaBassa ottavaBassaVb quindicesima quindicesimaAlta
""".split()

ANCHORS = ["stemUpSE", "stemDownNW", "stemUpNW", "stemDownSW", "cutOutNE", "cutOutNW",
           "cutOutSE", "cutOutSW"]


def camel(name):
    out = name[0].upper() + name[1:]
    return out.replace("8th", "Eighth").replace("16th", "Sixteenth").replace(
        "32nd", "ThirtySecond").replace("64th", "SixtyFourth").replace("15ma", "Quindicesima") \
        .replace("8vb", "Ottava8vb").replace("8va", "Ottava8va")


def main():
    meta = json.load(open(sys.argv[1], encoding="utf-8"))
    names = json.load(open(sys.argv[2], encoding="utf-8"))
    bbox = meta["glyphBBoxes"]
    adv = meta["glyphAdvanceWidths"]
    anchors = meta["glyphsWithAnchors"]
    out = []
    w = out.append
    w("// Generated by tools/score/gen_bravura.py from Bravura %s's metadata; do not edit." % meta["fontVersion"])
    w("//! The SMuFL glyphs the engraver uses: code points, Bravura's boxes, advances and")
    w("//! anchors (staff spaces, y up as SMuFL gives them), and its engraving defaults.")
    w("")
    w("/// The font's version the table was read from.")
    w('pub const BRAVURA_VERSION: &str = "%s";' % meta["fontVersion"])
    w("")
    w("/// Bravura's `engravingDefaults`, in staff spaces.")
    w("pub mod defaults {")
    for k, v in sorted(meta["engravingDefaults"].items()):
        if isinstance(v, (int, float)):
            snake = "".join("_" + c.lower() if c.isupper() else c for c in k).upper()
            w("    pub const %s: f32 = %r;" % (snake, float(v)))
    w("}")
    w("")
    w("/// A glyph of the music font.")
    w("#[derive(Copy, Clone, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]")
    w("pub enum Glyph {")
    for g in GLYPHS:
        w("    %s," % camel(g))
    w("}")
    w("")
    w("/// What the engraver reads of a glyph.")
    w("#[derive(Copy, Clone, Debug, PartialEq)]")
    w("pub struct Meta {")
    w("    pub name: &'static str,")
    w("    pub codepoint: char,")
    w("    /// South-west and north-east corners: `[x0, y0, x1, y1]`, y up.")
    w("    pub bbox: [f32; 4],")
    w("    pub advance: f32,")
    w("    /// `stemUpSE`, `stemDownNW`, `stemUpNW`, `stemDownSW`, `cutOutNE`, `cutOutNW`,")
    w("    /// `cutOutSE`, `cutOutSW` — `[x, y]`, or NaN where the glyph has none.")
    w("    pub anchors: [[f32; 2]; 8],")
    w("}")
    w("")
    w("const N: [f32; 2] = [f32::NAN, f32::NAN];")
    w("")
    w("/// Every glyph's metadata, in the enum's order.")
    w("pub const META: [Meta; %d] = [" % len(GLYPHS))
    for g in GLYPHS:
        cp = names[g]["codepoint"].replace("U+", "")
        b = bbox[g]
        box = [b["bBoxSW"][0], b["bBoxSW"][1], b["bBoxNE"][0], b["bBoxNE"][1]]
        a = anchors.get(g, {})
        an = ", ".join("[%r, %r]" % tuple(float(x) for x in a[k]) if k in a else "N" for k in ANCHORS)
        w("    Meta {")
        w('        name: "%s",' % g)
        w("        codepoint: '\\u{%s}'," % cp)
        w("        bbox: [%s]," % ", ".join(repr(float(x)) for x in box))
        w("        advance: %r," % float(adv.get(g, box[2])))
        w("        anchors: [%s]," % an)
        w("    },")
    w("];")
    w("")
    w("impl Glyph {")
    w("    /// Every glyph, in the table's order.")
    w("    pub const ALL: [Glyph; %d] = [" % len(GLYPHS))
    for g in GLYPHS:
        w("        Glyph::%s," % camel(g))
    w("    ];")
    w("}")
    sys.stdout.buffer.write(("\n".join(out) + "\n").encode("utf-8"))


main()
