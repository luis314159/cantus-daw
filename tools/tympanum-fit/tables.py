"""The measured voice's tables as Rust data (round 40, tymp-engine).

    python -I tables.py <fit.json> <out.rs> [gains.json]

Each table is one physical piece: one set of modes shared by every state and velocity
layer (a mode a layer lacks has amplitude 0 there), so the engine's cymbal is one object
whose new hits add to what is ringing. `gains.json` holds each table's level correction,
measured by rendering through the engine (calibrate.py).
"""
import json
import sys
import numpy as np

# id, name, [(piece in the fit, openness, foot)]
TABLES = [
    (1, "CRASH", [("crash", 0.0, False)]),
    (2, "HAT", [("hat_closed", 0.0, False), ("hat_o25", 0.25, False), ("hat_o50", 0.5, False),
                ("hat_o75", 0.75, False), ("hat_open", 0.95, False), ("hat_pedal", 0.0, True)]),
    (3, "RIDE", [("ride", 0.0, False), ("ride_bell", 1.0, False)]),
    (4, "KICK", [("kick", 0.0, False)]),
    (5, "SNARE", [("snare", 0.0, False), ("rimshot", 0.5, False), ("sidestick", 1.0, False)]),
    (6, "TOM_HI", [("tom_hi", 0.0, False)]),
    (7, "TOM_MID", [("tom_mid", 0.0, False)]),
    (8, "TOM_FLOOR", [("tom_floor", 0.0, False)]),
]
MAX_MODES = 512


def union(layers):
    """Cluster every layer's modes by frequency: (hz, t60) per union mode, and per layer
    its amplitude, rise and direct part; then (round 40, drums-gen) per layer its onset's
    phase, early amplitude and early phase (zeros where the layer has none), and the
    members `(layer, index in its modes)`."""
    allm = sorted((md[0], li, j, md) for li, lay in enumerate(layers)
                  for j, md in enumerate(lay["modes"]))
    groups = []
    for hz, li, j, md in allm:
        # one member per layer: two partials of one layer stay two (merged, they would be
        # one partial as strong as both)
        if (groups and hz - groups[-1]["hz"][-1] < max(6.0, 0.0025 * hz)
                and all(l != li for l, _, _ in groups[-1]["m"])):
            groups[-1]["hz"].append(hz)
            groups[-1]["m"].append((li, j, md))
        else:
            groups.append(dict(hz=[hz], m=[(li, j, md)]))
    rows = []
    for g in groups:
        nl = len(layers)
        amp = np.zeros(nl)
        rise = np.zeros(nl)
        direct = np.ones(nl)
        ph, ea, ep = np.zeros(nl), np.zeros(nl), np.zeros(nl)
        t60 = float(np.median([md[2] for _, _, md in g["m"]]))
        lt60 = np.full(nl, t60)
        for li, j, md in g["m"]:
            a = float(np.hypot(amp[li], md[1]))
            if md[1] >= amp[li]:
                rise[li], direct[li], lt60[li] = md[3], md[4], md[2]
                lay = layers[li]
                if lay.get("ets", 0.0) > 0 and "ph" in lay:
                    ph[li], ea[li], ep[li] = lay["ph"][j], lay["ea"][j], lay["ep"][j]
            amp[li] = a
        rows.append((float(np.mean(g["hz"])), t60, amp, rise, direct, lt60, ph, ea, ep,
                     [(li, j) for li, j, _ in g["m"]]))
    # A layer a mode is absent from rings it as that layer's own modes ring near it (the
    # median of its T60s within an octave): a closed hat's state must not lend the open
    # one's partials the open one's seconds when a stroke blends the two (drums-gen: a
    # nearly closed hat's blend kept 300 partials ringing 2.6 s, stroke on stroke).
    for li, lay in enumerate(layers):
        own = np.array([[md[0], md[2]] for md in lay["modes"]]) if lay["modes"] else None
        for r in rows:
            if any(l == li for l, _ in r[9]) or own is None:
                continue
            near = own[np.abs(np.log2(own[:, 0] / r[0])) <= 1.0, 1]
            r[5][li] = float(np.median(near if len(near) else own[:, 1]))
    rows.sort(key=lambda r: -r[2].max())
    # Grouped by the layers that have them (the first and the last), then by frequency:
    # the engine skips a block of eight modes none of which rings, so a stroke whose layers
    # own a few blocks pays for those, not for every state's partials interleaved by
    # frequency (drums-gen: a closed hat stroke ran the open states' 400 modes).
    def owners(r):
        has = [li for li in range(len(layers)) if r[2][li] > 0]
        return (has[0], has[-1]) if has else (len(layers), len(layers))
    rows = sorted(rows[:MAX_MODES], key=lambda r: (owners(r), r[0]))
    return rows


def fl(x, fmt):
    return ", ".join(format(float(v), fmt) for v in x)


def emit(fit, gains):
    nb, nbp = len(fit["centres"]), len(fit["bp_ms"])
    out = ["// @generated by the round-40 measuring tool (tools/tympanum-fit: fit.py, tables.py) from",
           "// DRSKit 2.1 - the DrumGizmo team (Deva and Lars Muldjord) and Jes Eiler of DRSDrums,",
           "// CC BY 4.0 (https://creativecommons.org/licenses/by/4.0/): parameters measured from",
           "// its recordings (no sample of it is here). Do not edit by hand.",
           "",
           "#![allow(clippy::excessive_precision, clippy::approx_constant)]",
           "",
           "use super::{Layer, State, Table};",
           "",
           f"pub(crate) const NB: usize = {nb};",
           f"pub(crate) const NBP: usize = {nbp};",
           f"pub(crate) static CENTRES: [f32; NB] = [{fl(fit['centres'], '.2f')}];",
           f"pub(crate) static BP_MS: [f32; NBP] = [{fl(fit['bp_ms'], '.1f')}];",
           ""]
    names = []
    for tid, name, parts in TABLES:
        # The states the fit has (a hat's half-open states are optional).
        parts = [x for x in parts if x[0] in fit["pieces"]]
        if not parts:
            continue
        layers, where = [], []
        for si, (p, op, foot) in enumerate(parts):
            for lay in fit["pieces"][p]:
                where.append((si, lay))
                layers.append(lay)
        rows = union(layers)
        n = len(rows)
        # the modes' trim through the engine (calibrate.py)
        trim = gains.get(f"{name}_MODES", 1.0)
        rows = [(r[0], r[1], r[2] * trim) + tuple(r[3:]) for r in rows]
        out.append(f"static {name}_HZ: [f32; {n}] = [{fl([r[0] for r in rows], '.3f')}];")
        states = []
        for si, (p, op, foot) in enumerate(parts):
            lays = []
            for li, (sj, lay) in enumerate(where):
                if sj != si:
                    continue
                tag = f"{name}_{si}_{li}"
                env = np.array(lay["env"]).reshape(-1)
                out.append(f"static {tag}_ENV: [f32; {nb * nbp}] = [{fl(np.maximum(env, -160), '.1f')}];")
                out.append(f"static {tag}_AMP: [f32; {n}] = [{fl([r[2][li] for r in rows], '.4e')}];")
                out.append(f"static {tag}_RISE: [f32; {n}] = [{fl([r[3][li] for r in rows], '.4f')}];")
                out.append(f"static {tag}_T60: [f32; {n}] = [{fl([r[5][li] for r in rows], '.4f')}];")
                out.append(f"static {tag}_DIRECT: [f32; {n}] = [{fl([r[4][li] for r in rows], '.3f')}];")
                lays.append(f"Layer {{ vel: {lay['vel']:.1f}, level: {lay.get('level', 0.0):.2f}, "
                            f"stick: [{fl(lay['stick'], '.4e')}], env: &{tag}_ENV, amp: &{tag}_AMP, "
                            f"t60: &{tag}_T60, rise: &{tag}_RISE, direct: &{tag}_DIRECT, "
                            f"glide: [{fl(lay.get('glide', [0.0, 0.05]), '.4f')}] }}")
            states.append(f"State {{ openness: {op:.2f}, foot: {str(foot).lower()}, layers: &[\n        "
                          + ",\n        ".join(lays) + "] }")
        out.append(f"pub(crate) static {name}: Table = Table {{ id: {tid}, hat: {str(name == 'HAT').lower()}, drum: {str(tid >= 4).lower()}, gain_db: "
                   f"{gains.get(name, 0.0):.2f}, hz: &{name}_HZ, states: &[\n    "
                   + ",\n    ".join(states) + "] };")
        out.append("")
        names.append(name)
    out.append(f"pub(crate) static TABLES: [&Table; {len(names)}] = [{', '.join('&' + x for x in names)}];")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    fit = json.load(open(sys.argv[1]))
    gains = json.load(open(sys.argv[3])) if len(sys.argv) > 3 else {}
    open(sys.argv[2], "w", newline="\n").write(emit(fit, gains))
