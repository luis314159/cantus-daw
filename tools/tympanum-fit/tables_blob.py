"""Model 5's tables as the engine's compact blob (round 40, tymp-engine).

    python -I tables_blob.py <fit.json> <dir> [gains.json]

Writes <dir>/pulsus_measured_tables.rs (the bands and breakpoints) and
<dir>/pulsus_measured.bin (format `CMT1` version 2, cantus-dsp/src/pulsus_measured_data.rs:
version 2 adds each layer's onset — its modes' phases and early parts, early.py).
"""
import json
import os
import struct
import sys
import numpy as np
sys.path.insert(0, __file__.rsplit("/", 1)[0].rsplit("\\", 1)[0])
from tables import TABLES, union, fl


def header(fit):
    nb, nbp = len(fit["centres"]), len(fit["bp_ms"])
    return "\n".join([
        "// @generated by the round-40 measuring tool (tools/tympanum-fit: fit.py, tables_blob.py):",
        "// the bands and breakpoints of `pulsus_measured.bin`, whose tables are measured from",
        "// DRSKit 2.1's recordings - the DrumGizmo team (Deva and Lars Muldjord) and Jes Eiler of",
        "// DRSDrums, CC BY 4.0 (no sample of it is here). Do not edit by hand.",
        "",
        "#![allow(clippy::excessive_precision)]",
        "",
        f"pub(crate) const NB: usize = {nb};",
        f"pub(crate) const NBP: usize = {nbp};",
        f"pub(crate) static CENTRES: [f32; NB] = [{fl(fit['centres'], '.4f')}];",
        f"pub(crate) static BP_MS: [f32; NBP] = [{fl(fit['bp_ms'], '.1f')}];",
        ""])


# How long a hat's partial takes to grow in when calibrate_hat.py says it rang too much at
# once and the fit gave it no rise of its own (s).
RISE_HAT = 0.03


def no_swell(env, bp):
    """No band swells after its peak (drums-gen 2; the ladder's finding behind the owner's
    "iuuu": 40 of 128 layers rose 2.2-3.2 s after the hit, +11...+22 dB — a later event in the
    measuring render, and bands fitted on the recording's floor, pulled into the last
    breakpoints): past its peak a band never rises, and past 1 s it falls at least as fast
    as it did from 300 ms (or its peak) to 1 s."""
    env = np.array(env, dtype=float)
    k1 = int(np.argmin(np.abs(bp - 1000.0)))
    for b in range(env.shape[0]):
        e = env[b]
        if (e > -150.0).sum() < 3:
            continue
        i = int(np.argmax(e))
        for k in range(i + 1, len(e)):
            e[k] = min(e[k], e[k - 1])
        k0 = int(np.argmax(bp >= max(bp[i], 300.0)))
        if k1 > k0 and e[k1] > -150.0:
            slope = (e[k1] - e[k0]) / (bp[k1] - bp[k0])
            if slope < 0:
                for k in range(k1 + 1, len(e)):
                    e[k] = min(e[k], e[k - 1] + slope * (bp[k] - bp[k - 1]))
    return env


def blob(sources):
    """`sources`: (fit, gains, id offset) — the studio kit's DRSKit tables at 0, the jazz
    kit's Virtuosity tables at 16."""
    fit0 = sources[0][0]
    nb, nbp = len(fit0["centres"]), len(fit0["bp_ms"])
    tabs = []
    for fit, gains, off in sources:
        assert len(fit["centres"]) == nb and len(fit["bp_ms"]) == nbp
        for tid, name, parts in TABLES:
            parts = [x for x in parts if x[0] in fit["pieces"]]
            if parts:
                tabs.append((fit, gains, off, tid, name, parts))
    o = bytearray(b"CMT1")
    o += struct.pack("<IIII", 2, nb, nbp, len(tabs))
    for fit, gains, off, tid, name, parts in tabs:
        layers, where = [], []
        for si, (p, op, foot) in enumerate(parts):
            for lay in fit["pieces"][p]:
                where.append(si)
                layers.append(lay)
        rows = union(layers)
        trim = gains.get(f"{name}_MODES", 1.0)
        n = len(rows)
        o += struct.pack("<BBBBfI", tid + off, name == "HAT", tid >= 4, 0, gains.get(name, 0.0), n)
        o += struct.pack(f"<{n}f", *[r[0] for r in rows])
        o += struct.pack("<I", len(parts))
        for si, (p, op, foot) in enumerate(parts):
            lis = [li for li, sj in enumerate(where) if sj == si]
            o += struct.pack("<fBBBBI", op, foot, 0, 0, 0, len(lis))
            # a state's own trim on top of the table's (the ride's bow)
            st = trim * gains.get(f"{name}_MODES_{si}", 1.0)
            for li in lis:
                lay = layers[li]
                gl = lay.get("glide", [0.0, 0.05])
                ld = gains.get(f"{name}_LEVEL_{si}_{int(lay['vel'])}", 0.0)
                # the stick through the engine (calibrate_stick.py): burst and knock
                sk = gains.get(f"{name}_STICK_{si}_{int(lay['vel'])}", [1.0, 1.0])
                stick = [lay["stick"][0] * sk[0], lay["stick"][1] * sk[1]]
                o += struct.pack("<6f", lay["vel"], lay.get("level", 0.0), *stick, *gl)
                env = np.array(lay["env"], dtype=float).reshape(nb, nbp)
                # the engine's colour corrected band by band (calibrate_bands.py): per
                # band, per region of the hit (attack, body, tail)
                band = gains.get(f"{name}_BAND_{si}_{int(lay['vel'])}")
                if band is not None:
                    from calibrate_bands import REGIONS
                    corr = np.array(band, dtype=float).reshape(nb, len(REGIONS))
                    bp = np.array(fit["bp_ms"], dtype=float)
                    for r, ((lo_ms, hi_ms), _) in enumerate(REGIONS):
                        k = (bp >= lo_ms) & (bp <= hi_ms)
                        live = env[:, k] > -150.0
                        env[:, k] = np.where(live, env[:, k] + corr[:, r:r + 1], env[:, k])
                # a drum's noise at `lo`-`hi` Hz falls past its peak at least 60 dB in `t60` s
                # (drums-gen 3, cue 5: after the colour's corrections, which had lifted the
                # toms' 1-4 kHz tail back to 0.9-1.6 s against DRSKit's 0.35-0.45)
                dec = gains.get(f"{name}_DECAY")
                if dec is not None:
                    lo, hi, t60 = dec
                    bp = np.array(fit["bp_ms"], dtype=float)
                    for b, c in enumerate(fit["centres"]):
                        if lo <= c <= hi:
                            k = int(np.argmax(env[b]))
                            cap = env[b, k] - 60.0 * (bp - bp[k]) / 1000.0 / t60
                            tail = (np.arange(nbp) > k) & (env[b] > -150.0)
                            env[b] = np.where(tail, np.minimum(env[b], cap), env[b])
                env = no_swell(env, np.array(fit["bp_ms"], dtype=float))
                env = np.round(np.maximum(env.reshape(-1) + ld, -160.0) * 100)
                o += struct.pack(f"<{nb * nbp}h", *[int(x) for x in np.clip(env, -32768, 32767)])
                ld = gains.get(f"{name}_LEVEL_{si}_{int(lay['vel'])}", 0.0)
                lt = st * gains.get(f"{name}_MODES_{si}_{int(lay['vel'])}", 1.0) * 10 ** (ld / 20)
                # a cymbal's partials region by region (calibrate_tonal.py)
                tonal = gains.get(f"{name}_TONAL_{si}_{int(lay['vel'])}")

                def tf(hz, tonal=tonal):
                    if tonal is None:
                        return 1.0
                    from fit import REGIONS as FREG
                    return next((tonal[i] for i, (a, b) in enumerate(FREG) if a <= hz < b), 1.0)
                o += struct.pack(f"<{n}f", *[float(r[2][li] * lt * tf(r[0])) for r in rows])
                # a hat state's partials' T60s trimmed (calibrate_hat.py)
                kt = gains.get(f"{name}_T60_{si}_{int(lay['vel'])}", 1.0)
                o += struct.pack(f"<{n}H", *[int(np.clip(round(r[5][li] * kt * 1000), 0, 65535)) for r in rows])
                # a hat layer's share struck at once, trimmed (calibrate_hat.py): a partial
                # that rang at once grows in over RISE_HAT instead
                kd = gains.get(f"{name}_DIRECT_{si}_{int(lay['vel'])}", 1.0)
                rise = [r[3][li] if kd >= 1.0 or r[3][li] > 0 else RISE_HAT for r in rows]
                direct = [min(r[4][li] * kd, 1.0) for r in rows]
                o += struct.pack(f"<{n}H", *[int(np.clip(round(x * 10000), 0, 65535)) for x in rise])
                o += struct.pack(f"<{n}B", *[int(np.clip(round(x * 255), 0, 255)) for x in direct])
                # version 2: the onset (early.py) — its time constant, 0 for none
                ets = float(lay.get("ets", 0.0))
                o += struct.pack("<f", ets)
                if ets > 0:
                    q = lambda a: int(np.clip(round(a * 10000), -32767, 32767))
                    o += struct.pack(f"<{n}h", *[q(r[6][li]) for r in rows])
                    o += struct.pack(f"<{n}f", *[float(r[7][li] * lt) for r in rows])
                    o += struct.pack(f"<{n}h", *[q(r[8][li]) for r in rows])
    return bytes(o)


if __name__ == "__main__":
    # tables_blob.py <dir> <fit.json> <gains.json> <offset> [<fit.json> <gains.json> <offset> ...]
    d = sys.argv[1]
    a = sys.argv[2:]
    sources = []
    for i in range(0, len(a), 3):
        g = a[i + 1]
        sources.append((json.load(open(a[i])), json.load(open(g)) if os.path.exists(g) else {}, int(a[i + 2])))
    open(os.path.join(d, "pulsus_measured_tables.rs"), "w", newline="\n").write(header(sources[0][0]))
    open(os.path.join(d, "pulsus_measured.bin"), "wb").write(blob(sources))
