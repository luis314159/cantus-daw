"""Every key a candidate spec may set, read from the Rust source (so it never goes stale):
`Voicing::set`'s names, the field each one writes, its doc comment, beta.14's value (what an
empty spec plays) and candidate 16's (what ships). Writes Markdown.

    python -I knobs.py [<repo root>] > KNOBS.md
"""
import os
import re
import sys

ROOT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
SRC = os.path.join(ROOT, 'crates', 'cantus-dsp', 'src')
C16 = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'candidates', 'c16', 'spec.txt')


def read(name):
    return open(os.path.join(SRC, name), encoding='utf-8').read()


def struct_docs(text, name):
    """field -> doc comment (a comment shared by consecutive fields goes to each)."""
    body = re.search(r'pub struct ' + name + r' \{(.*?)\n\}', text, re.S).group(1)
    docs, cur, last = {}, [], ''
    for line in body.split('\n'):
        s = line.strip()
        if s.startswith('///'):
            if not cur:
                last = ''
            cur.append(s[3:].strip())
        elif s.startswith('pub '):
            f = re.match(r'pub (\w+):', s).group(1)
            if cur:
                last = ' '.join(cur)
                cur = []
            docs[f] = last
    # beta.14's fields that share a comment declared before an interrupting one
    for f in ('polar', 'polar_ct', 'polar_yz', 'polar_damp', 'loose_last'):
        if f in docs and 'uni_weight' in docs:
            docs[f] = docs['uni_weight']
    return docs


def beta14(text, ty):
    body = re.search(r'pub fn beta14\(\) -> Self \{\s*' + ty + r' \{(.*?)\n        \}', text, re.S).group(1)
    vals = {}
    for m in re.finditer(r'^\s*(\w+): (.+?),\s*$', body, re.M):
        vals[m.group(1)] = m.group(2)
    return vals


def value(vals, field, idx):
    v = vals.get(field)
    if v is None:
        return ''
    if idx is None:
        return v
    m = re.match(r'\[(.*)\]$', v)
    if m and ';' not in v:
        parts = [p.strip() for p in m.group(1).split(',')]
        return parts[idx] if idx < len(parts) else ''
    if v.startswith('super::'):
        return '`' + v[len('super::'):] + '`'
    m = re.match(r'\[(.*); \w+\]$', v)
    return m.group(1) if m else v


def main():
    sys.stdout.reconfigure(encoding='utf-8', newline='\n')
    v = read('chorda_voicing.rs')
    docs = {'': struct_docs(v, 'Voicing'), 'body': struct_docs(read('chorda_body.rs'), 'BodyVoicing'),
            'room': struct_docs(read('chorda_room.rs'), 'RoomVoicing')}
    b14 = {'': beta14(v, 'Voicing'), 'body': beta14(read('chorda_body.rs'), 'BodyVoicing'),
           'room': beta14(read('chorda_room.rs'), 'RoomVoicing')}
    c16 = {}
    for kv in open(C16, encoding='utf-8').readline().strip().split(','):
        k, x = kv.split('=')
        c16[k] = x  # a later key overrides an earlier one, as the lab applies it
    setfn = re.search(r'pub fn set\(&mut self.*?\n    \}\n', v, re.S).group(0)
    print('# Chorda voicing knobs (generated by `knobs.py` from `crates/cantus-dsp/src/chorda_voicing.rs`)\n')
    print('A spec is one line `key=value,key=value,…`, applied in order over beta.14\'s voicing (a later')
    print('key overrides an earlier one). "beta.14" is what an empty spec plays; "c16" what candidate 16')
    print('(the shipped voicing since `DSP_VERSION` 7) sets, blank where it leaves beta.14\'s value.\n')
    print('| key | field | beta.14 | c16 | meaning |')
    print('|---|---|---|---|---|')
    for m in re.finditer(r'"([\w.]+)" => &mut self\.((?:body|room)\.)?(\w+)(?:\[(\d+)\])?', setfn):
        key, grp, field, idx = m.group(1), (m.group(2) or '').rstrip('.'), m.group(3), m.group(4)
        idx = int(idx) if idx is not None else None
        d = docs[grp].get(field, '').replace('|', '\\|')
        fname = (grp + '.' if grp else '') + field + (f'[{idx}]' if idx is not None else '')
        print(f'| `{key}` | `{fname}` | {value(b14[grp], field, idx)} | {c16.get(key, "")} | {d} |')
    # the families the match does not list one by one
    print('| `reg.<bass\\|mid\\|treble>.<0..6>` | `reg[r][band]` | 0 | (see spec) | ' + docs[''].get('reg', '') + ' |')
    print('| `reg.<bass\\|mid\\|treble>.level` | `reg_level[r]` | 0 | (see spec) | ' + docs[''].get('reg_level', '') + ' |')
    print('| `draw.<21..108>` | `draws[key-21]` | 0 | (see spec) | ' + docs[''].get('draws', '').replace('|', '\\|') + ' |')
    print('| `hf_key.<21..108>` | `hf_keys[key-21]` | 1 | (see spec) | ' + docs[''].get('hf_keys', '').replace('|', '\\|') + ' |')
    print('\nNot in a spec: the two tables, `CHORDA_PARTIALS` (each key\'s partials 2…7, dB, scaled by')
    print('`partials_amount`) and `CHORDA_LEVELS` (each key\'s level, dB, scaled by `levels_amount`) — see SPEC.md.')
    unknown = [k for k in c16 if not re.search(r'"' + re.escape(k) + r'"', setfn)
               and not re.match(r'(reg\.(bass|mid|treble)\.(\d|level)|draw\.\d+|hf_key\.\d+)$', k)]
    if unknown:
        print('\nc16 keys the parser did not find (check the generator):', ', '.join(unknown))


if __name__ == '__main__':
    main()
