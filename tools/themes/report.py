"""Measure every theme and write it as Rust (`themes.py --write`)."""

from pathlib import Path

import build
import check
from colour import ensure_all, to_hex, contrast

FN = {"slate": "pewter", "paper": "chalk", "ink_gold": "ink_and_gold"}
RESTORED = ["cantus_night", "cantus_paper", "daylight", "blue_hour", "ultraviolet", "lagoon",
            "slate", "paper", "ink_gold", "parchment"]


def fn_name(id_):
    return FN.get(id_, id_)


def palette_accents(t):
    """The old palette's text-legible accent (4.5:1 on the panel and the canvas) and its
    bright tone for the large readouts (3:1 on the panel)."""
    acc = ensure_all(t["highlight"], [t["panel"], t["ink"]], 4.5)
    bright = ensure_all(t["brand_bright"], [t["panel"]], 3.0)
    return acc, bright


def emit_tokens(id_, s, t):
    lines = ["pub const fn %s_tokens() -> Tokens {" % fn_name(id_), "    Tokens {"]
    for k in build.FIELDS:
        if k in ("dark", "radius", "round", "depth", "density", "text_scale", "generation", "system"):
            continue
        lines.append("        %s: %s," % (k, build.rs_colour(t[k])))
    lines += [
        "        dark: %s," % ("true" if s["dark"] else "false"),
        "        radius: %.1f," % s.get("radius", 4.0),
        "        round: 1.0,",
        "        depth: 0.5,",
        "        density: 1.0,",
        "        text_scale: 1.0,",
        "        generation: 0,",
        "        system: %s," % s["system"],
        "    }",
        "}",
    ]
    return lines


def emit_theme(id_, s, t):
    acc, bright = palette_accents(t)
    return [
        "pub fn %s() -> Theme {" % fn_name(id_),
        "    family(",
        '        "%s",' % s["name"],
        "        %s_tokens()," % fn_name(id_),
        "        hex(0x%s)," % to_hex(acc),
        "        hex(0x%s)," % to_hex(bright),
        "    )",
        "}",
    ]


def main(specs, write):
    built = {}
    bad_any = False
    for id_, s in specs.items():
        t = build.make(s)
        acc, bright = palette_accents(t)
        bad = check.failures(t, acc, bright)
        built[id_] = t
        flag = "FAIL" if bad else "ok"
        bad_any |= bool(bad)
        print("%-16s %-4s panel %s bar %s well %s text %s dim %s accent %s"
              % (id_, flag, to_hex(t["panel"]), to_hex(t["toolbar"]), to_hex(t["well"]),
                 to_hex(t["text"]), to_hex(t["text_dim"]), to_hex(t["highlight"])))
        for m in s.get("moved", []):
            print("    moved", m)
        for b in bad:
            print("    BAD", b)
    if write and not bad_any:
        root = build.ROOT / "crates/cantus-ui/src"
        import docs

        for path, ids, head in [
            (root / "theme_redrawn.rs", RESTORED, docs.RESTORED),
            (root / "theme_added.rs", [i for i in specs if i not in RESTORED], docs.ADDED),
        ]:
            out = head.strip().splitlines() + [
                "//!",
                "//! Generated by `tools/themes/themes.py --write`; change the spec there, not here.",
            ]
            prelude = docs.PRELUDE
            if not any("CableStyle" in specs[i]["system"] for i in ids):
                prelude = prelude.replace("{CableStyle, System}", "System")
            out += prelude.rstrip().splitlines() + [""]
            for id_ in ids:
                out += ["/// %s's tokens (see the module's documentation)." % specs[id_]["name"]]
                out += emit_tokens(id_, specs[id_], built[id_]) + [""]
                out += ["/// %s." % specs[id_]["name"]]
                out += emit_theme(id_, specs[id_], built[id_]) + [""]
            path.write_text("\n".join(out).rstrip() + "\n", encoding="utf-8")
            print("wrote", path)
    return built
