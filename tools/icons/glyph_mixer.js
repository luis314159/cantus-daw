// Generates crates/cantus-ui/src/kit/glyph_mixer_data.rs from the icon family's mixer set
// (set 3, `docs/round39/design/icons/glyphs-m-mixer*.js`, approved by the owner).
// `node tools/icons/glyph_mixer.js <icons design dir> > crates/cantus-ui/src/kit/glyph_mixer_data.rs`
const fs = require('fs');
const path = require('path');
const dir = process.argv[2];
global.window = {};
const src = ['family.js', 'glyphs-n-transport.js', 'glyphs-m-mixer.js', 'glyphs-m-mixer2.js']
  .map(f => fs.readFileSync(path.join(dir, f), 'utf8')).join('\n;\n');
// Browser scripts share one global scope: run them as one, then read N.
const N = new Function('window', src + '\n;return N;')(window);
const want = ['phase', 'swap', 'mono', 'link', 'arm', 'enable', 'fx', 'send', 'out', 'into', 'ret',
  'key', 'routing', 'freeze', 'vca', 'lamp', 'lampOff', 'grip', 'miniView', 'more', 'add',
  'foldOpen', 'foldShut'];
let out = '//! Set 3 of the icon family, the mixer strip and inspector glyphs (round 39, `icons`,\n' +
  '//! approved 2026-11-09): every glyph as drawn for each device size it is placed at.\n' +
  '//! Generated by `tools/icons/glyph_mixer.js` from `glyphs-m-mixer*.js`; edit the design,\n' +
  '//! not this file. Inks are named (`var(--main)` …), as in `icons_data`.\n\n' +
  '/// (name, canvas side in device pixels, SVG body).\n' +
  'pub const DRAWINGS: &[(&str, u16, &str)] = &[\n';
const missing = [];
for (const n of want) {
  const g = N[n];
  if (!g) { missing.push(n); continue; }
  for (const k of Object.keys(g).map(Number).sort((a, b) => a - b)) {
    const body = window.drawing(g[k]).replace(/"#/g, '" #');
    out += `    ("${n}", ${k}, r#"${body}"#),\n`;
  }
}
out += '];\n';
if (missing.length) console.error('missing: ' + missing.join(' '));
process.stdout.write(out);
