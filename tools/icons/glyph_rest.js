// Generates crates/cantus-ui/src/kit/glyph_rest_data.rs from the icon family's set 5, the
// rest of `glyph.rs` (`docs/round39/design/icons/glyphs-r-*.js`, spec-rest.md), with the
// set-4 drawings the Glyph map names (star, starFilled, check).
// `node tools/icons/glyph_rest.js <icons design dir> > crates/cantus-ui/src/kit/glyph_rest_data.rs`
const fs = require('fs');
const path = require('path');
const dir = process.argv[2];
global.window = {};
const read = f => fs.readFileSync(path.join(dir, f), 'utf8');
const v1 = ['glyphs-transport.js', 'glyphs-transport2.js', 'glyphs-tools.js', 'glyphs-tools2.js',
  'glyphs-tools3.js'].map(f => read(path.join('v1', f))).join('\n;\n');
const src = ['family.js', 'glyphs-n-transport.js', 'glyphs-n-transport2.js', 'glyphs-n-tools.js',
  'glyphs-n-tools2.js', 'glyphs-n-windows.js', 'glyphs-m-mixer.js', 'glyphs-m-mixer2.js',
  'glyphs-b-browser.js', 'glyphs-b-browser2.js', 'glyphs-r-rest.js', 'glyphs-r-small.js',
  'glyphs-r-rest2.js'].map(read).join('\n;\n');
// Browser scripts share one global scope: run them as one, then read N.
const N = new Function('window', v1 + '\n;window.G1 = G;\n;' + src + '\n;return N;')(window);
const want = ['help', 'warning', 'agent', 'device', 'keyboard', 'score', 'mouseMenu', 'automate',
  'filter', 'replace', 'warp', 'pluginStopped', 'controller', 'lanePencil', 'laneLine',
  'laneCurve', 'session', 'stage', 'sliders', 'menu', 'down', 'next', 'prev', 'close', 'minimise',
  'maximise', 'restore', 'resizeGrip', 'resize', 'typed', 'sendOpen', 'star', 'starFilled',
  'check'];
let out = '//! Set 5 of the icon family, the rest of `glyph.rs` (round 39, `icons`, spec-rest.md),\n' +
  '//! and the set-4 drawings the kit\'s glyph map names: every glyph as drawn for each device\n' +
  '//! size it is placed at. Generated by `tools/icons/glyph_rest.js` from `glyphs-r-*.js`;\n' +
  '//! edit the design, not this file. Inks are named (`var(--main)` …), as in `icons_data`.\n\n' +
  '/// (name, canvas side in device pixels, SVG body).\n' +
  'pub const DRAWINGS: &[(&str, u16, &str)] = &[\n';
const missing = [];
for (const n of want) {
  const g = N[n];
  if (!g) { missing.push(n); continue; }
  for (const k of Object.keys(g).map(Number).sort((a, b) => a - b)) {
    const body = window.drawing(g[k]).replace(/"#/g, '" #');
    if (!body) { missing.push(`${n}@${k}`); continue; }
    out += `    ("${n}", ${k}, r#"${body}"#),\n`;
  }
}
out += '];\n';
if (missing.length) console.error('missing: ' + missing.join(' '));
process.stdout.write(out);
