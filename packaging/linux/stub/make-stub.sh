#!/bin/bash
# A stand-in libpipewire for a system that has none (ADR 0065, packaging/linux/README.md):
# every function the given programs take from the real library, each returning zero (a
# null pointer, `false`, nothing), and every data symbol as zeroed bytes. The programs then
# load; the PipeWire host is never offered (it needs PipeWire's socket), and if it were
# tried, `pw_context_new` and its kin answer null and cpal reports the host unavailable.
#
#   make-stub.sh <real libpipewire-0.3.so.0> <out .so> <program>...
set -euo pipefail
real="$1"
out="$2"
shift 2
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
for p in "$@"; do nm -D --undefined-only "$p" | awk '{print $NF}'; done | sed 's/@.*//' |
  sort -u >"$work/wanted"
nm -D --defined-only "$real" | awk '{print $2, $3}' | sed 's/@.*//' | sort -k2 -u >"$work/has"
{
  echo "/* Generated by packaging/linux/stub/make-stub.sh from $(basename "$real"). */"
  awk 'NR == FNR { want[$1] = 1; next }
       ($2 in want) {
         if ($1 == "T" || $1 == "t" || $1 == "W" || $1 == "i")
           printf "void *%s(void) { return 0; }\n", $2;
         else
           printf "char %s[256];\n", $2;
       }' "$work/wanted" "$work/has"
} >"$work/stub.c"
count=$(grep -c "^void\|^char" "$work/stub.c" || true)
[ "$count" -gt 0 ] || {
  echo "the programs take nothing from $real"
  exit 1
}
gcc -shared -fPIC -O1 -w -Wl,-soname,libpipewire-0.3.so.0 -o "$out" "$work/stub.c"
echo "stub $out: $count symbols"
